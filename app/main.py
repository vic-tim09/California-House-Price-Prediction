"""HTTP endpoints for SmartHouse AI."""

from fastapi import FastAPI, HTTPException

from app.model_service import load_model, predict_one, read_metrics
from app.schemas import (
    BatchPredictionRequest,
    BatchPredictionResponse,
    HouseFeatures,
    PredictionResponse,
)

app = FastAPI(
    title="SmartHouse AI",
    description=(
        "A machine-learning API that estimates median California census block-group "
        "house values from demographic and housing features. This is an educational "
        "estimate, not a real-estate appraisal."
    ),
    version="1.0.0",
)


@app.get("/", tags=["General"])
def home() -> dict[str, str]:
    """Provide a quick introduction and documentation links."""
    return {
        "project": "SmartHouse AI",
        "status": "running",
        "docs": "/docs",
        "health": "/health",
        "prediction_endpoint": "POST /predict",
    }


@app.get("/health", tags=["General"])
def health() -> dict[str, str | bool]:
    """Check API health without requiring a trained model to be present."""
    try:
        load_model()
        model_loaded = True
    except (FileNotFoundError, OSError, ValueError):
        model_loaded = False

    return {
        "status": "ok",
        "model_loaded": model_loaded,
        "hint": "Run python training.py if model_loaded is false.",
    }


@app.get("/model-info", tags=["Model"])
def model_info() -> dict:
    """Expose the actual metrics generated by training.py."""
    try:
        return read_metrics()
    except FileNotFoundError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc


@app.post("/predict", response_model=PredictionResponse, tags=["Prediction"])
def predict(house: HouseFeatures) -> PredictionResponse:
    """Predict the median house value for one census block group."""
    usd = predict_one(house.model_dump())
    return PredictionResponse(estimated_median_house_value_usd=usd)


@app.post(
    "/predict/batch",
    response_model=BatchPredictionResponse,
    tags=["Prediction"],
)
def predict_batch(request: BatchPredictionRequest) -> BatchPredictionResponse:
    """Predict up to 50 records in one request."""
    results = [
        PredictionResponse(estimated_median_house_value_usd=predict_one(house.model_dump()))
        for house in request.houses
    ]
    return BatchPredictionResponse(predictions=results, count=len(results))
